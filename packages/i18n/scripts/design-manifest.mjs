// Classification manifest for extract-from-design.mjs: every leaf in the
// design's ghi-data.js / ghi-data-2.js is listed here, or the run fails.
//
// Directives (for a leaf):
//   "ns.key"         copy -> locale key (design text, "{x}" -> "{{x}}")
//   "@reason"        ignore; "@icon: ..." / "@id: ..." are counted as dropped
//   "~file.json#a.b" sample data -> packages/ui/mocks/file.json
//   ">ns.key"        same text as an existing key (verified), no new key
//   { k, ... }       options:
//     v      {x: "name"}  rename "{x}" placeholders
//     sub    [[from, to]] (or {en, vi}) replace text with "{{var}}"; checked via vars
//     tpl    [en, vi]     hand-written template ({one, other} for EN plurals)
//     vars   check values ({en, vi} when numbers are formatted differently)
//     one    [from, to]   EN singular form of the plural (VI has only "other")
//     calls  [{args, vars}] how a design function renders (verified)
//     plat   true | {en, vi}  split into key_mac / key_win (true: derived by rule)
//     ctx    "mac"|"win"  the design already has a per-platform string
//     also   second leaf from the same source (a function with two outputs)
//     mockVars "f.json#p"  write the check vars as sample data
//     macOnly / neutral    guard exemptions (see the script)
// Arrays are positional, objects are keyed; `$pairs: true` means each child is
// an [EN, VI] pair.

