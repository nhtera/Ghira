// Writes src/fonts.css: @font-face rules for the bundled fonts (OFL-1.1), only
// the latin, latin-ext and vietnamese subsets (the @fontsource CSS would also
// bundle cyrillic and greek files). Run after a font package update:
//   pnpm --filter @ghi/ui gen:fonts
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, "../src/fonts.css");
const require = createRequire(import.meta.url);
const SUBSETS = ["latin", "latin-ext", "vietnamese"];

/** [package, css file inside it] */
const SOURCES = [
  ["@fontsource/be-vietnam-pro", ["400.css", "500.css", "600.css"]],
  ["@fontsource-variable/source-serif-4", ["opsz.css", "opsz-italic.css"]],
  ["@fontsource-variable/geist-mono", ["index.css"]],
];

const rules = [];
for (const [pkg, files] of SOURCES) {
  const root = dirname(require.resolve(`${pkg}/package.json`));
  for (const file of files) {
    const css = readFileSync(join(root, file), "utf8");
    for (const m of css.matchAll(/\/\* ([\w-]+) \*\/\s*(@font-face \{[^}]*\})/g)) {
      const [, name, rule] = m;
      if (!SUBSETS.some((s) => name.includes(`-${s}-`))) continue;
      // Package-relative URLs, resolved by Vite from this file.
      const fixed = rule.replace(/url\(\.\/files\/([^)]+)\)/g, (_, f) => {
        const target = join(root, "files", f);
        return `url(${relative(dirname(out), target).split("\\").join("/").replace(/^.*node_modules\//, "../node_modules/")})`;
      });
      // woff2 only (every supported WebView reads it): no .woff fallbacks shipped.
      rules.push(`/* ${name} */\n${fixed.replace(/,\s*url\([^)]+\.woff\) format\('woff'\)/g, "")}`);
    }
  }
}
const header =
  "/* SPDX-License-Identifier: Apache-2.0 */\n" +
  "/* Generated by scripts/build-fonts-css.mjs: do not edit. Fonts: OFL-1.1 (licenses in the font packages). */\n\n";
writeFileSync(out, header + rules.join("\n\n") + "\n");
console.log(`wrote ${rules.length} @font-face rules to ${relative(process.cwd(), out)}`);
